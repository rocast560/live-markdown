export function calloutStyle(type: string): { color: string; icon: string } {
  const [color, ic] = CALLOUTS[type.toLowerCase()] ?? CALLOUTS.note;
  return { color: color === "gray" ? "#9e9e9e" : `var(--color-${color})`, icon: ic };
}
