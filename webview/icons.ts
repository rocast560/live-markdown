export function icon(name: string, className = "lm-icon"): SVGSVGElement {
  const wrapper = document.createElement("span");
  wrapper.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${className}">${PATHS[name] ?? PATHS.pencil}</svg>`;
  return wrapper.firstChild as SVGSVGElement;
}

